function getLangStrings(lang) {
  return BUILTIN_LANGUAGE[lang] || BUILTIN_LANGUAGE[DEFAULT_LANG];
}

function localizeLookup(map, key, lang) {
  return map?.[key]?.[lang] || map?.[key]?.[DEFAULT_LANG] || null;
}

function formatSegment(label, value) {
  return label ? `${label}: ${value}` : value;
}

function buildDisplayText(segments) {
  return segments.map((segment) => segment.text).join(' | ');
}

function buildResult(rawCode, source, segments, topicRef = null) {
  return {
    rawCode,
    source,
    segments,
    displayText: buildDisplayText(segments),
    topicRef,
  };
}

function decodeCompactCode(rawCode, lang) {
  const strings = getLangStrings(lang);
  const normalizedCode = String(rawCode || '').trim();
  const tokens = normalizedCode.split('.').filter(Boolean);
  if (tokens.length === 0) return null;

  const [first, ...rest] = tokens;
  if (!normalizedCode.includes('.') && !strings.values.partOfSpeech[first]) return null;
  const segments = [];
  const partOfSpeech = strings.values.partOfSpeech[first];
  if (partOfSpeech) {
    segments.push({
      kind: 'partOfSpeech',
      code: first,
      text: formatSegment(strings.categories.partOfSpeech, partOfSpeech),
    });
  } else if (tokens.some((token) => token.length > 1)) {
    segments.push({
      kind: 'unknown',
      code: first,
      text: formatSegment(strings.categories.unknown, first),
    });
  } else {
    return null;
  }

  for (const token of rest) {
    const normalized = token.toLowerCase();
    let kind = null;
    let value = null;

    for (const candidate of [
      'stem',
      'aspect',
      'tense',
      'voice',
      'mood',
      'person',
      'gender',
      'number',
      'state',
      'case',
      'degree',
      'suffix',
    ]) {
      const match = strings.values[candidate]?.[normalized];
      if (match) {
        kind = candidate;
        value = match;
        break;
      }
    }

    if (!kind) {
      segments.push({
        kind: 'unknown',
        code: token,
        text: formatSegment(strings.categories.unknown, token),
      });
      continue;
    }

    segments.push({
      kind,
      code: token,
      text: formatSegment(strings.categories[kind], value),
    });
  }

  return buildResult(rawCode, 'builtin-compact', segments);
}

function decodeRobinsonCode(rawCode, lang) {
  const strings = getLangStrings(lang);
  const code = String(rawCode || '')
    .trim()
    .toUpperCase();
  if (!/^[A-Z](?:-[A-Z0-9]+)+$/.test(code)) return null;

  const [part, ...rest] = code.split('-');
  if (!ROBINSON_PARTS[part]) return null;
  const segments = [];
  const partLabel = localizeLookup(ROBINSON_VALUES.partOfSpeech, part, lang);
  if (partLabel) {
    segments.push({
      kind: 'partOfSpeech',
      code: part,
      text: formatSegment(strings.categories.partOfSpeech, partLabel),
    });
  }

  const firstBlock = rest[0] || '';
  if (firstBlock && /^[NGDAVBL][SPD][MFN]$/.test(firstBlock)) {
    const [caseCode, numberCode, genderCode] = firstBlock.split('');
    const triplet = [
      ['case', caseCode],
      ['number', numberCode],
      ['gender', genderCode],
    ];
    for (const [kind, token] of triplet) {
      const label = localizeLookup(ROBINSON_VALUES[kind], token, lang);
      if (!label) continue;
      segments.push({
        kind,
        code: token,
        text: formatSegment(strings.categories[kind], label),
      });
    }
    if (rest[1]) {
      const degree = localizeLookup(ROBINSON_VALUES.degree, rest[1], lang);
      if (degree) {
        segments.push({
          kind: 'degree',
          code: rest[1],
          text: formatSegment(strings.categories.degree, degree),
        });
      } else {
        segments.push({
          kind: 'unknown',
          code: rest[1],
          text: formatSegment(strings.categories.unknown, rest[1]),
        });
      }
    }
    return buildResult(rawCode, 'builtin-robinson', segments);
  }

  if (part === 'V' && firstBlock && /^[PIFAXYRLT][AMPDENU][ISOMNPRDGU]$/.test(firstBlock)) {
    const [tenseCode, voiceCode, moodCode] = firstBlock.split('');
    const triplet = [
      ['tense', tenseCode],
      ['voice', voiceCode],
      ['mood', moodCode],
    ];
    for (const [kind, token] of triplet) {
      const label = localizeLookup(ROBINSON_VALUES[kind], token, lang);
      if (!label) continue;
      segments.push({
        kind,
        code: token,
        text: formatSegment(strings.categories[kind], label),
      });
    }
    if (rest[1] && /^[123][SPD]$/.test(rest[1])) {
      const [personCode, numberCode] = rest[1].split('');
      const person = localizeLookup(ROBINSON_VALUES.person, personCode, lang);
      const number = localizeLookup(ROBINSON_VALUES.number, numberCode, lang);
      if (person) {
        segments.push({
          kind: 'person',
          code: personCode,
          text: formatSegment(strings.categories.person, person),
        });
      }
      if (number) {
        segments.push({
          kind: 'number',
          code: numberCode,
          text: formatSegment(strings.categories.number, number),
        });
      }
    }
    return buildResult(rawCode, 'builtin-robinson', segments);
  }

  return null;
}

function decodeBsbCode(rawCode, lang) {
  const strings = getLangStrings(lang);
  const code = String(rawCode || '').trim();
  if (!/^[A-Za-z]+(?:-[A-Za-z0-9]+)+$/.test(code)) return null;
  const [part, ...rest] = code.split('-');
  if (!part) return null;

  const normalizedPart = part.toLowerCase();
  const partValue = strings.values.partOfSpeech[normalizedPart] || part;
  const segments = [
    {
      kind: 'partOfSpeech',
      code: part,
      text: formatSegment(strings.categories.partOfSpeech, partValue),
    },
  ];

  const codes = rest[0] || '';
  if (/^[NGDAVBL][MFN][SPD]$/.test(codes)) {
    const [caseCode, genderCode, numberCode] = codes.toUpperCase().split('');
    const mapped = [
      ['case', caseCode],
      ['gender', genderCode],
      ['number', numberCode],
    ];
    for (const [kind, token] of mapped) {
      const label = localizeLookup(ROBINSON_VALUES[kind], token, lang);
      if (!label) continue;
      segments.push({
        kind,
        code: token,
        text: formatSegment(strings.categories[kind], label),
      });
    }
    if (rest[1]) {
      const degree = localizeLookup(ROBINSON_VALUES.degree, rest[1].toUpperCase(), lang);
      if (degree) {
        segments.push({
          kind: 'degree',
          code: rest[1],
          text: formatSegment(strings.categories.degree, degree),
        });
      }
    }
    return buildResult(rawCode, 'builtin-bsb', segments);
  }

  if (/^[PIFAXYRLT][AMPDENU][ISOMNPRDGU]$/.test(codes)) {
    const [tenseCode, voiceCode, moodCode] = codes.toUpperCase().split('');
    const triplet = [
      ['tense', tenseCode],
      ['voice', voiceCode],
      ['mood', moodCode],
    ];
    for (const [kind, token] of triplet) {
      const label = localizeLookup(ROBINSON_VALUES[kind], token, lang);
      if (!label) continue;
      segments.push({
        kind,
        code: token,
        text: formatSegment(strings.categories[kind], label),
      });
    }
    if (rest[1] && /^[123][SPD]$/.test(rest[1])) {
      const [personCode, numberCode] = rest[1].split('');
      const person = localizeLookup(ROBINSON_VALUES.person, personCode, lang);
      const number = localizeLookup(ROBINSON_VALUES.number, numberCode, lang);
      if (person) {
        segments.push({
          kind: 'person',
          code: personCode,
          text: formatSegment(strings.categories.person, person),
        });
      }
      if (number) {
        segments.push({
          kind: 'number',
          code: numberCode,
          text: formatSegment(strings.categories.number, number),
        });
      }
    }
    return buildResult(rawCode, 'builtin-bsb', segments);
  }

  return null;
}

function parseMorphologyMeaning(rawCode, lang) {
  return (
    decodeCompactCode(rawCode, lang) ||
    decodeRobinsonCode(rawCode, lang) ||
    decodeBsbCode(rawCode, lang)
  );
}

function preferredLookupLanguages({ uiLanguage, dictLanguage }) {
  const langs = [];
  const push = (value) => {
    const normalized = String(value || '')
      .trim()
      .toLowerCase();
    if (!normalized || langs.includes(normalized)) return;
    langs.push(normalized);
  };
  push(dictLanguage);
  push(uiLanguage);
  push('en');
  push('');
  return langs;
}

function queryMorphologyMeaning(db, hasLanguageColumn, indication, applicableTo, lang) {
  const applicableValues = applicableTo ? [applicableTo, ''] : [''];
  const conditions = [];
  const params = [indication];
  if (hasLanguageColumn) {
    if (lang === '') {
      conditions.push("(language IS NULL OR trim(language) = '')");
    } else {
      conditions.push('lower(language) = ?');
      params.push(lang);
    }
  }
  conditions.push(`applicable_to IN (${applicableValues.map(() => '?').join(', ')})`);
  params.push(...applicableValues);
  const sql = `
    SELECT indication, applicable_to AS applicableTo, ${hasLanguageColumn ? 'language,' : "'' AS language,"} meaning
    FROM morphology_indications
    WHERE indication = ?
      AND ${conditions.join(' AND ')}
    ORDER BY CASE applicable_to WHEN ? THEN 0 ELSE 1 END
    LIMIT 1
  `;
  params.push(applicableTo || '');
  return db.prepare(sql).get(...params) || null;
}

function resolveMorphologyTopic(db, indication) {
  try {
    const row = db
      .prepare('SELECT topic FROM morphology_topics WHERE indication = ? LIMIT 1')
      .get(indication);
    return row?.topic || null;
  } catch (_) {
    return null;
  }
}

function splitMorphCode(rawCode) {
  return String(rawCode || '')
    .trim()
    .split(/[.\-]/)
    .filter(Boolean);
}

function resolveFromModuleTables(db, rawCode, langs, hasLanguageColumn) {
  const parts = splitMorphCode(rawCode);
  if (parts.length === 0) return null;

  for (const lang of langs) {
    const segments = [];
    let matchedAny = false;
    for (let i = 0; i < parts.length; i++) {
      const token = parts[i];
      const applicableTo = i === 0 ? '' : parts[0];
      const row = queryMorphologyMeaning(db, hasLanguageColumn, token, applicableTo, lang);
      if (!row) {
        segments.push({
          kind: 'unknown',
          code: token,
          text: token,
        });
        continue;
      }
      matchedAny = true;
      const text = row.applicableTo
        ? `${getLangStrings(lang || DEFAULT_LANG).applicableTo} ${row.applicableTo}: ${row.meaning}`
        : row.meaning;
      segments.push({
        kind: 'table',
        code: token,
        text,
      });
    }
    if (matchedAny) {
      return buildResult(rawCode, 'table', segments, resolveMorphologyTopic(db, rawCode));
    }
  }

  return null;
}

function normalizeUiLanguage(value) {
  return (
    String(value || DEFAULT_LANG)
      .trim()
      .toLowerCase()
      .slice(0, 2) || DEFAULT_LANG
  );
}

function resolveMorphology({ bibleHandle, dictHandle, morphCode, uiLanguage }) {
  const rawCode = String(morphCode || '').trim();
  const lang = normalizeUiLanguage(uiLanguage);
  if (!rawCode) return null;

  const dictLanguage = dictHandle?.info?.language || dictHandle?.info?.articles_language || '';
  const langs = preferredLookupLanguages({ uiLanguage: lang, dictLanguage });

  if (bibleHandle?.morphology?.hasIndications) {
    const tableResult = resolveFromModuleTables(
      bibleHandle.db,
      rawCode,
      langs,
      bibleHandle.morphology.hasLanguageColumn
    );
    if (tableResult) {
      return { ...tableResult, source: 'bible-table' };
    }
  }

  if (dictHandle?.morphology?.hasIndications) {
    const tableResult = resolveFromModuleTables(
      dictHandle.db,
      rawCode,
      [dictLanguage.toLowerCase(), ''],
      false
    );
    if (tableResult) {
      return { ...tableResult, source: 'dict-table' };
    }
  }

  return (
    parseMorphologyMeaning(rawCode, lang) || {
      rawCode,
      source: 'unknown',
      segments: [{ kind: 'unknown', code: rawCode, text: rawCode }],
      displayText: rawCode,
      topicRef: null,
    }
  );
}

