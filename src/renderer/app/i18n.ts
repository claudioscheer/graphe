  function isSupportedLang(lang: string | null): lang is SupportedLang {
    return lang === 'pt' || lang === 'en' || lang === 'es';
  }

  function getCurrentLang(): SupportedLang {
    const lang = localStorage.getItem('graphe-lang');
    return isSupportedLang(lang) ? lang : 'pt';
  }

  function setLang(lang: string): void {
    localStorage.setItem('graphe-lang', isSupportedLang(lang) ? lang : 'pt');
    updateAll();
  }

  function t(key: string): string {
    const lang = getCurrentLang();
    return (translations[lang] && translations[lang][key]) || translations.en[key] || key;
  }

  function updateAll(): void {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      el.textContent = t(key || '');
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement) {
        el.placeholder = t(key || '');
      }
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      if (el instanceof HTMLElement || el instanceof SVGElement) {
        el.setAttribute('title', t(key || ''));
      }
    });
  }

  function bookName(bookNumber: number): LocalizedBookName {
    const idx = _bookNumberToIndex.get(bookNumber);
    if (idx == null) return { short: String(bookNumber), long: String(bookNumber) };
    const lang = getCurrentLang();
    const names = bookNames[lang] || bookNames.en;
    return names[idx] || { short: String(bookNumber), long: String(bookNumber) };
  }

  function stripDiacritics(str: string): string {
    return str.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  }

  function findBookByAbbrev(abbrev: string): number | null {
    const lang = getCurrentLang();
    const names = bookNames[lang] || bookNames.en;
    const lower = stripDiacritics(abbrev.toLowerCase());
    // Exact match first (e.g. "jo" → "Jo" João, not "Jó" Job)
    for (let i = 0; i < names.length; i++) {
      const s = stripDiacritics(names[i].short.toLowerCase());
      if (s === lower) return BOOK_NUMBERS[i];
    }
    // Then prefix match
    for (let i = 0; i < names.length; i++) {
      const s = stripDiacritics(names[i].short.toLowerCase());
      if (s.startsWith(lower)) return BOOK_NUMBERS[i];
    }
    return null;
  }

  return {
    getCurrentLang,
    setLang,
    t,
    updateAll,
    bookName,
    findBookByAbbrev,
    _bookNames: bookNames,
    _BOOK_NUMBERS: BOOK_NUMBERS,
  };
