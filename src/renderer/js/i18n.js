  function getCurrentLang() {
    return localStorage.getItem('graphe-lang') || 'pt';
  }

  function setLang(lang) {
    localStorage.setItem('graphe-lang', lang);
    updateAll();
  }

  function t(key) {
    const lang = getCurrentLang();
    return (translations[lang] && translations[lang][key]) || translations.en[key] || key;
  }

  function updateAll() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.placeholder = t(key);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      el.title = t(key);
    });
  }

  function bookName(bookNumber) {
    const idx = _bookNumberToIndex.get(bookNumber);
    if (idx == null) return { short: String(bookNumber), long: String(bookNumber) };
    const lang = getCurrentLang();
    const names = bookNames[lang] || bookNames.en;
    return names[idx] || { short: String(bookNumber), long: String(bookNumber) };
  }

  function findBookByAbbrev(abbrev) {
    const lang = getCurrentLang();
    const names = bookNames[lang] || bookNames.en;
    const lower = abbrev.toLowerCase();
    for (let i = 0; i < names.length; i++) {
      const s = names[i].short.toLowerCase();
      if (s === lower || s.startsWith(lower)) return BOOK_NUMBERS[i];
    }
    return null;
  }

  return { getCurrentLang, setLang, t, updateAll, bookName, findBookByAbbrev };
